CREATE TABLE supplier_product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES supplier(id),
    sku text NOT NULL REFERENCES product(sku),
    unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    active boolean NOT NULL DEFAULT true,
    UNIQUE(supplier_id, sku)
);
CREATE INDEX ix_supplier_product_sku ON supplier_product(sku);
ALTER TABLE supplier_product ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON supplier_product FROM anon, authenticated, PUBLIC;
