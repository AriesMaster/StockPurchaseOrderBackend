
-- StockFlow authentication and authorization schema.

CREATE TABLE app_user (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          email TEXT NOT NULL UNIQUE,
                          password_hash TEXT,
                          role TEXT NOT NULL CHECK (
                              role IN (
                                       'ADMIN',
                                       'PURCHASING_OFFICER',
                                       'APPROVER',
                                       'WAREHOUSE_OFFICER'
                                  )
                              ),
                          enabled BOOLEAN NOT NULL DEFAULT FALSE,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

                          CHECK (email = LOWER(BTRIM(email))),
                          CHECK (BTRIM(email) <> ''),
                          CHECK (NOT enabled OR password_hash IS NOT NULL)
);

CREATE TABLE auth_session (
                              id UUID PRIMARY KEY,
                              user_id BIGINT NOT NULL REFERENCES app_user(id),
                              created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                              expires_at TIMESTAMPTZ NOT NULL,
                              revoked_at TIMESTAMPTZ,

                              CHECK (expires_at > created_at)
);

CREATE TABLE refresh_token (
                               token_digest VARCHAR(64) PRIMARY KEY,
                               session_id UUID NOT NULL REFERENCES auth_session(id),
                               created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                               expires_at TIMESTAMPTZ NOT NULL,
                               consumed_at TIMESTAMPTZ,

                               CHECK (expires_at > created_at)
);

CREATE TABLE account_token (
                               token_digest VARCHAR(64) PRIMARY KEY,
                               user_id BIGINT NOT NULL REFERENCES app_user(id),
                               purpose TEXT NOT NULL CHECK (
                                   purpose IN ('INVITE', 'RESET')
                                   ),
                               created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                               expires_at TIMESTAMPTZ NOT NULL,
                               consumed_at TIMESTAMPTZ,

                               CHECK (expires_at > created_at)
);

-- Indexes

CREATE INDEX ix_auth_session_user_id
    ON auth_session(user_id);

CREATE INDEX ix_refresh_token_session_id
    ON refresh_token(session_id);

CREATE INDEX ix_account_token_user_id
    ON account_token(user_id);

-- Enable row-level security.

ALTER TABLE app_user ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_session ENABLE ROW LEVEL SECURITY;
ALTER TABLE refresh_token ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_token ENABLE ROW LEVEL SECURITY;

-- Prevent direct access through Supabase client roles.

REVOKE ALL ON
    app_user,
    auth_session,
    refresh_token,
    account_token
    FROM anon, authenticated, PUBLIC;
