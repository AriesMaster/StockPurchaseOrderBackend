CREATE TABLE app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND email <> ''),
    password_hash text,
    role text NOT NULL CHECK (role IN ('ADMIN', 'PURCHASING_OFFICER', 'APPROVER', 'WAREHOUSE_OFFICER')),
    enabled boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (NOT enabled OR password_hash IS NOT NULL)
);
CREATE TABLE auth_session (
    id uuid PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app_user(id),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz
);
CREATE TABLE refresh_token (
    digest varchar(64) PRIMARY KEY CHECK (length(digest) = 64),
    session_id uuid NOT NULL REFERENCES auth_session(id),
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz
);
CREATE TABLE account_token (
    digest varchar(64) PRIMARY KEY CHECK (length(digest) = 64),
    user_id bigint NOT NULL REFERENCES app_user(id),
    purpose text NOT NULL CHECK (purpose IN ('INVITE', 'RESET')),
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz
);
CREATE INDEX ix_auth_session_user ON auth_session(user_id);
CREATE INDEX ix_refresh_token_session ON refresh_token(session_id);
CREATE INDEX ix_account_token_user ON account_token(user_id);
ALTER TABLE app_user ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_session ENABLE ROW LEVEL SECURITY;
ALTER TABLE refresh_token ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_token ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON app_user, auth_session, refresh_token, account_token FROM anon, authenticated, PUBLIC;
REVOKE ALL ON SEQUENCE app_user_id_seq FROM anon, authenticated, PUBLIC;
