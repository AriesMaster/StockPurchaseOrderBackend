-- StockFlow first-release schema. All quantities are whole units.
CREATE TABLE product (
    sku text PRIMARY KEY CHECK (btrim(sku) <> ''),
    name text NOT NULL CHECK (btrim(name) <> '')
);

CREATE TABLE purchase_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status text NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'APPROVED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE purchase_order_line (
    purchase_order_id bigint NOT NULL REFERENCES purchase_order(id),
    sku text NOT NULL REFERENCES product(sku),
    ordered_quantity integer NOT NULL CHECK (ordered_quantity > 0),
    received_quantity integer NOT NULL DEFAULT 0,
    PRIMARY KEY (purchase_order_id, sku),
    CHECK (received_quantity >= 0 AND received_quantity <= ordered_quantity)
);

CREATE TABLE receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES purchase_order(id),
    idempotency_key text NOT NULL CHECK (btrim(idempotency_key) <> ''),
    request_fingerprint text NOT NULL CHECK (btrim(request_fingerprint) <> ''),
    recorded_at timestamptz NOT NULL DEFAULT now(),
    order_status_after text NOT NULL CHECK (order_status_after IN ('PARTIALLY_RECEIVED', 'RECEIVED')),
    UNIQUE (purchase_order_id, idempotency_key),
    UNIQUE (id, purchase_order_id)
);

CREATE TABLE receipt_line (
    receipt_id bigint NOT NULL,
    purchase_order_id bigint NOT NULL,
    sku text NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    outstanding_quantity_after integer NOT NULL CHECK (outstanding_quantity_after >= 0),
    PRIMARY KEY (receipt_id, sku),
    FOREIGN KEY (receipt_id, purchase_order_id) REFERENCES receipt(id, purchase_order_id),
    FOREIGN KEY (purchase_order_id, sku) REFERENCES purchase_order_line(purchase_order_id, sku)
);

CREATE TABLE inventory_balance (
    sku text PRIMARY KEY REFERENCES product(sku),
    quantity_on_hand integer NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0)
);

CREATE TABLE stock_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL,
    sku text NOT NULL,
    quantity_change integer NOT NULL CHECK (quantity_change > 0),
    recorded_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (receipt_id, sku),
    FOREIGN KEY (receipt_id, sku) REFERENCES receipt_line(receipt_id, sku)
);

CREATE INDEX ix_purchase_order_line_sku ON purchase_order_line(sku);
CREATE INDEX ix_receipt_line_order_sku ON receipt_line(purchase_order_id, sku);
CREATE INDEX ix_stock_movement_sku_recorded_at ON stock_movement(sku, recorded_at);

